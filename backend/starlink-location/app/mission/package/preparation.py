"""One owned export assembly worker with persisted deadlines and snapshot downloads."""

import json
import logging
import threading
import time
from contextlib import nullcontext
from datetime import datetime, timezone
from hashlib import sha256
from uuid import uuid4

from app.mission.exporter.export_cancel import check_cancelled
from app.mission.exporter.snapshot_inputs import canonical_json
from app.mission.slide_cache.capture import capture_raw
from app.mission.slide_cache.identity import renderer_revision
from app.mission.slide_cache.store import default_store

from .archive_files import ArchiveFiles
from .customer_artifacts import (
    CustomerBriefingOutcome,
    MissionPackageDownload,
    build_mission_package_download,
)
from .frozen_planning import CaptureCancel, capture_planning
from .json_stream import iter_json
from .preparation_store import ExportPreparation, PreparationStore
from .preparation_worker import PreparationWorker

logger = logging.getLogger(__name__)
from .preparation_store import TERMINAL


class ExportPreparationService(PreparationWorker):
    def __init__(
        self,
        route_manager,
        poi_manager,
        *,
        enabled,
        cache=None,
        clock=time.time,
        builder=None,
        archive_capture=None,
        archive_capture_owned=None,
    ):
        self.route_manager, self.poi_manager = route_manager, poi_manager
        self.enabled, self.clock = enabled, clock
        self.archive_capture = archive_capture
        self.archive_capture_owned = archive_capture_owned
        self.capture_guard = threading.Lock()
        self.builder = builder or build_mission_package_download
        self.cache = cache or default_store()
        self.jobs = PreparationStore(self.cache)
        self.files = ArchiveFiles(self.cache, clock=clock)
        self.artifacts = self.cache.path.parent / "exports"
        self.artifacts.mkdir(mode=0o700, exist_ok=True)
        self.stop, self.wake, self.guard = (
            threading.Event(),
            threading.Event(),
            threading.RLock(),
        )
        self.captures = {}
        self.executing = set()
        self.thread = threading.Thread(
            target=self.run, name="mission-export-assembly", daemon=True
        )
        self.thread.start()

    def path(self, job_id):
        # IDs are generated by this service; lookups are scoped in the database first.
        return self.artifacts / f"{job_id}.zip"

    def capture_revision(self):
        enabled = self.enabled() if callable(self.enabled) else self.enabled
        return renderer_revision() + (":enabled" if enabled else ":disabled")

    def capture(self, mission_id):
        from app.mission.slide_cache.persisted_pois import persisted_pois

        return capture_raw(
            mission_id,
            self.route_manager,
            persisted_pois(self.poi_manager),
            self.capture_revision(),
        )

    @staticmethod
    def fingerprint(raw, archive=None):
        archive_identity = (
            None
            if archive is None
            else {
                "schema_version": archive["schema_version"],
                "files": archive["files"],
                "attachments": [
                    {k: v for k, v in attachment.items() if k != "id"}
                    for attachment in archive.get("attachments", [])
                ],
                "components": {
                    name: {
                        k: v
                        for k, v in component.items()
                        if k not in ("capture_started_at", "capture_finished_at")
                    }
                    for name, component in archive["components"].items()
                },
            }
        )
        identity = sha256()
        if archive is not None:
            for chunk in iter_json(archive_identity, compact=True):
                identity.update(chunk.encode("ascii"))
        identity.update(raw.metadata)
        identity.update(canonical_json(raw.dependency_token[0]))
        identity.update(raw.dependency_token[1])
        identity.update(raw.renderer_revision.encode())
        return identity.hexdigest()

    def start(self, mission_id, *, telemetry_format="full", cancel=None):
        if telemetry_format not in ("full", "compact"):
            raise ValueError("Unknown telemetry format")
        if not self.capture_guard.acquire(blocking=False):
            raise RuntimeError("Archive capture already in progress; retry")
        try:

            def check():
                check_cancelled(cancel)
                check_cancelled(self.stop)

            ownership = (
                self.files.capture(check=check)
                if self.archive_capture_owned
                else nullcontext(None)
            )
            with ownership as owner:
                return self._start(
                    mission_id,
                    owner=owner,
                    telemetry_format=telemetry_format,
                    cancel=CaptureCancel(owner.check if owner else check),
                )
        finally:
            self.capture_guard.release()

    def _start(self, mission_id, *, owner=None, telemetry_format="full", cancel=None):
        if self.stop.is_set():
            raise RuntimeError("Export preparation is stopping")
        now = self.clock()
        capture_started = time.monotonic()
        raw = self.capture(mission_id)
        enabled = self.enabled() if callable(self.enabled) else self.enabled
        planning = capture_planning(raw, self.cache, enabled=enabled, cancel=cancel)
        if owner is not None:
            owner.leg_ids = tuple(leg.leg_id for leg in planning.snapshot.legs)
        planning_captured_at = self.clock()
        archive = (
            self.archive_capture_owned(mission_id, owner, telemetry_format)
            if self.archive_capture_owned
            else self.archive_capture(mission_id) if self.archive_capture else None
        )
        if archive is not None:
            archive = {
                **archive,
                "components": {
                    **archive["components"],
                    "planning": {
                        "capture_started_at": datetime.fromtimestamp(
                            now, timezone.utc
                        ).isoformat(),
                        "capture_finished_at": datetime.fromtimestamp(
                            planning_captured_at, timezone.utc
                        ).isoformat(),
                        "fingerprint": planning.snapshot.fingerprint,
                        "metadata_sha256": sha256(raw.metadata).hexdigest(),
                    },
                },
            }
        fingerprint = self.fingerprint(raw, archive)
        metadata = json.loads(raw.metadata)
        revision = (
            metadata.get("metadata", {}).get("itinerary_planning", {}).get("revision")
        )
        with self.guard:
            for old in self.jobs.all():
                if (
                    old.mission_id == mission_id
                    and old.fingerprint == fingerprint
                    and old.state == "ready"
                    and old.briefing_status != "omitted"
                    and old.expires_at > now
                    and self.path(old.id).exists()
                ):
                    return old
            job = ExportPreparation(
                id=uuid4().hex,
                mission_id=mission_id,
                state="queued",
                fingerprint=fingerprint,
                revision=revision,
                snapshot_policy="captured",
                queued_at=now,
                deadline=now + 600,
                stage_timings={"capture": time.monotonic() - capture_started},
            )
            self.jobs.write(job, archive=archive, owner=owner, planning=planning)
            self.captures[job.id] = raw
            self.wake.set()
            return job

    def status(self, mission_id, job_id):
        with self.guard:
            job = self.jobs.read(mission_id, job_id)
            if job.state not in TERMINAL and self.clock() >= job.deadline:
                job = job.model_copy(
                    update={
                        "state": "failed",
                        "stage": "failed",
                        "error_code": "deadline",
                        "finished_at": self.clock(),
                    }
                )
                self.jobs.write_pending(job)
            if job.state == "ready" and self.clock() >= job.expires_at:
                job = job.model_copy(
                    update={
                        "state": "expired",
                        "stage": "expired",
                        "download_url": None,
                    }
                )
                self.jobs.write(job)
            if job.state == "expired":
                self.files.expire_download(job)
            if job.state not in TERMINAL:
                job.leg_states = {
                    leg: record["state"]
                    for leg, record in self.cache.status_records(mission_id).items()
                }
            if job.state in TERMINAL and job_id not in self.executing:
                self.captures.pop(job_id, None)
                if job.state != "ready":
                    self.jobs.discard_archive(job_id)
            return job

    def sweep_captures(self):
        with self.guard:
            terminal = {j.id for j in self.jobs.all() if j.state in TERMINAL}
            for job_id in list(self.captures):
                if job_id in terminal and job_id not in self.executing:
                    self.captures.pop(job_id, None)

    def cancel(self, mission_id, job_id):
        with self.guard:
            job = self.status(mission_id, job_id)
            if job.state not in TERMINAL:
                job = job.model_copy(
                    update={
                        "state": "cancelled",
                        "stage": "cancelled",
                        "finished_at": self.clock(),
                    }
                )
                if not self.jobs.write_pending(job):
                    return self.jobs.read(mission_id, job_id)
            if job_id not in self.executing:
                self.captures.pop(job_id, None)
                if job.state != "ready":
                    self.jobs.discard_archive(job_id)
            self.wake.set()
            return job

    def open_download(self, mission_id, job_id):
        with self.guard:
            job = self.status(mission_id, job_id)
            if job.state == "expired":
                raise TimeoutError("Export preparation expired")
            if job.state != "ready":
                raise ValueError("Export preparation is not ready")
            briefing = (
                CustomerBriefingOutcome(job.briefing_status, job.warning_code, None)
                if job.briefing_status
                else None
            )
            return MissionPackageDownload(self.files.open_download(job), briefing)

    def close(self):
        self.stop.set()
        self.wake.set()
        self.thread.join(25)
        if self.thread.is_alive():
            raise RuntimeError("Mission export assembly did not stop")
        for job in self.jobs.all():
            if job.id in self.captures and job.state not in TERMINAL:
                self.cancel(job.mission_id, job.id)
        self.captures.clear()
